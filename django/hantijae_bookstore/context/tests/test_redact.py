class RedactTest(SimpleTestCase):
    def test_must_mask(self):
        for text, expected in MUST_MASK:
            with self.subTest(text=text):
                self.assertEqual(redact(text)[0], expected)

    def test_must_keep(self):
        for text in MUST_KEEP:
            with self.subTest(text=text):
                self.assertEqual(redact(text), (text, {}))

    def test_address_does_not_eat_following_date(self):
        self.assertEqual(redact('중구 동성로 12에서 10월 3일 북토크')[0], '[주소]에서 10월 3일 북토크')

    def test_counts_per_rule(self):
        self.assertEqual(redact('010-1234-5678, 010-2222-3333 / 비번 xyz1')[1], {'phone': 2, 'password': 1})

    def test_empty(self):
        self.assertEqual(redact(None), ('', {}))
        self.assertEqual(redact(''), ('', {}))

    def test_token_after_email_is_kept_without_login_words(self):
        self.assertEqual(redact('메일 reader@example.com thanks')[0], '메일 [이메일] thanks')

    def test_long_messages_stay_fast(self):
        # 워커가 메시지마다 바로 가리므로 긴 글(띄어쓰기 없는 한글 등)에서 정규식이 폭주하면 안 된다
        samples = ['도' * 4096, '가' * 4096, 'a' * 4096, '비번 ' * 800, '1-' * 2048,
                   ('대구시중구동성로' * 600)[:4096], 'user' * 1000 + '@', ('비밀번호가 ' * 700)[:4096]]
        start = time.perf_counter()
        for s in samples:
            redact(s)
        self.assertLess(time.perf_counter() - start, 1.0)
